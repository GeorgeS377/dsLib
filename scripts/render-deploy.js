#!/usr/bin/env node
// Write the deployment files out of .env, instead of copying examples and
// editing them.
//
// The port lived in three places: PORT in .env, `proxy_pass 127.0.0.1:3000`
// in the Nginx site, and `curl localhost:3000/healthz` in the guide. Changing
// the first left Nginx proxying to a port nothing was listening on, with no
// error anywhere to say so — just a 502. The domain was worse: it existed
// only as `library.example.gr` with a "change this" comment beside it.
//
// So there is one source — .env, through src/config.js — and these files are
// generated from it. Generated, not edited: the header of each says so,
// because a hand-edited copy puts the two places back out of step.
//
// Usage:
//   npm run deploy:config                 writes deploy/out/
//   npm run deploy:config -- --print      writes nothing, shows what it would
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { config as defaultConfig, projectRoot } from '../src/config.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const templateDir = path.join(here, '..', 'deploy');

/** Replace every {{name}} with values[name], refusing to leave one behind. */
export function fill(template, values) {
  const missing = new Set();
  const out = template.replace(/\{\{\s*(\w+)\s*\}\}/g, (_match, name) => {
    if (!(name in values)) {
      missing.add(name);
      return `{{${name}}}`;
    }
    return String(values[name]);
  });
  if (missing.size > 0) {
    throw new Error(`Template has no value for: ${[...missing].join(', ')}`);
  }
  return out;
}

function banner(source) {
  return [
    `# Generated by \`npm run deploy:config\` from .env and ${source}.`,
    '# Edit .env and run it again rather than editing this file: a hand-edited',
    '# copy is how the port ends up meaning two different things.',
    '',
  ].join('\n');
}

function read(name) {
  return fs.readFileSync(path.join(templateDir, name), 'utf8');
}

/**
 * The Nginx site, with this deployment's domain and port in it.
 * @param {typeof defaultConfig} config
 */
export function renderNginxConf(config, { projectRoot: root = projectRoot } = {}) {
  return (
    banner('deploy/nginx-dslib.conf.template') +
    fill(read('nginx-dslib.conf.template'), {
      publicHost: config.publicHost,
      port: config.port,
      projectRoot: root,
    })
  );
}

/**
 * The systemd unit, with this deployment's install directory in it.
 * @param {typeof defaultConfig} config
 */
export function renderSystemdUnit(
  config,
  { projectRoot: root = projectRoot, user = 'dslib', nodePath = null } = {},
) {
  return (
    banner('deploy/dslib.service.template') +
    fill(read('dslib.service.template'), {
      projectRoot: root,
      user,
      port: config.port,
      publicHost: config.publicHost,
      // Whichever node is running this, which is the one the admin just used
      // to install and will use to run it. A hardcoded /usr/bin/node is wrong
      // on any machine that installed Node somewhere else, and systemd's only
      // complaint is a service that refuses to start.
      nodePath: nodePath ?? process.execPath,
    })
  );
}

function main(argv) {
  const config = defaultConfig;
  const printOnly = argv.includes('--print');
  const outDir = path.join(templateDir, 'out');

  const files = {
    'nginx-dslib.conf': renderNginxConf(config),
    'dslib.service': renderSystemdUnit(config),
  };

  if (config.publicUrlDerived) {
    console.warn(
      'PUBLIC_URL is not set, so these files name ' +
        `${config.publicHost} — fine locally, wrong behind Nginx.\n` +
        'Set PUBLIC_URL=https://your.domain in .env and run this again.\n',
    );
  }

  if (printOnly) {
    for (const [name, body] of Object.entries(files)) {
      console.log(`----- ${name} -----\n${body}`);
    }
    return;
  }

  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, body] of Object.entries(files)) {
    fs.writeFileSync(path.join(outDir, name), body, { mode: 0o644 });
  }

  console.log(
    `Wrote deploy/out/ for ${config.publicUrl} → 127.0.0.1:${config.port}\n\n` +
      '  sudo cp deploy/out/nginx-dslib.conf /etc/nginx/sites-available/dslib\n' +
      '  sudo cp deploy/out/dslib.service    /etc/systemd/system/dslib.service\n\n' +
      'Read them before installing them; nothing here touches your server.',
  );
}

// Only when run directly, so the test can import the renderers.
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main(process.argv.slice(2));
}
